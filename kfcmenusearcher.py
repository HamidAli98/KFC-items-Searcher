"""## Product Search and Recommendation System
This search system allows users to look up any McDonald's menu item. If the product isn't found exactly, it recommends the closest matching menu items available using string similarity and predicts their energy content using our Decision Tree Regressor.
"""

import difflib

def search_menu_product(query, df, model, features):
    """
    Searches for a menu item in the dataset.
    If not found, suggests similar products.
    """
    menu_items = df['Menu Items'].tolist()
    query_clean = query.strip().lower()

    # Check for exact or substring match first
    matches = [item for item in menu_items if query_clean in item.lower()]

    # If no substring matches, find closest spelling matches
    if not matches:
        matches = difflib.get_close_matches(query, menu_items, n=3, cutoff=0.3)
        if matches:
            print(f"\u274c '{query}' not found. Did you mean one of these available items?\n")
        else:
            print(f"\u274c '{query}' not found, and no close matches were found in the menu.\n")
            return
    else:
        print(f"\u2705 Found matching item(s) for '{query}':\n")

    # Display matching / suggested products with predicted calories
    for match in matches:
        row = df[df['Menu Items'] == match].iloc[0]

        # Prepare features for the prediction (handling potential NaN in sodium)
        row_prep = row.copy()
        if pd.isna(row_prep['"Sodium (mg)"']):
            row_prep['"Sodium (mg)"'] = df['"Sodium (mg)"'].median()

        feat_vector = pd.DataFrame([row_prep[features]])
        pred_calories = model.predict(feat_vector)[0]

        print(f"** Product: {row['Menu Items']} **")
        print(f" - Serving Size: {row['Per Serve Size']}")
        print(f" - Actual Energy: {row['Energy (kCal)']} kCal")
        print(f" - Predicted Energy (Decision Tree): {pred_calories:.2f} kCal")
        print(f" - Protein: {row['"Protein (g)"']}g | Total Fat: {row['"Total fat (g)"']}g | Carbs: {row['Total carbohydrate (g)']}g")
        print("-" * 50)

# Example Test Runs:
print("--- Test Case 1: Exact / Partial Match ---")
search_menu_product('McVeggie', mcd_prep, dt_model, features)

print("\n--- Test Case 2: Typo / Suggestion Match ---")
